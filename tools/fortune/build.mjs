// Builds src/client/resources/assets/sentils/fortune/fortune.js: Elite's farming-weight library
// plus adapter.js, as one script in old-style JavaScript that the mod's embedded engine can run.
//
//   cd tools/fortune && npm install && npm run build
//
// To pick up a SkyBlock farming update, change LIBRARY_COMMIT to a newer commit of
// https://github.com/EliteFarmers/Website and run the build again.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';
import ts from 'typescript';

const LIBRARY_REPO = 'https://github.com/EliteFarmers/Website.git';
const LIBRARY_COMMIT = '53839413cba5cc2a3765f437e97d34d0347fe48a';

const here = dirname(fileURLToPath(import.meta.url));
const checkout = join(here, '.library');
const output = join(here, '../../src/client/resources/assets/sentils/fortune/fortune.js');

const git = (...args) => execFileSync('git', args, { stdio: 'inherit' });
if (!existsSync(checkout)) {
	git('init', '--quiet', checkout);
	git('-C', checkout, 'remote', 'add', 'origin', LIBRARY_REPO);
}
git('-C', checkout, 'fetch', '--quiet', '--depth', '1', 'origin', LIBRARY_COMMIT);
git('-C', checkout, 'checkout', '--quiet', '--force', 'FETCH_HEAD');

const library = join(checkout, 'packages/farming-weight');
const version = JSON.parse(readFileSync(join(library, 'package.json'), 'utf8')).version;

const bundled = await build({
	entryPoints: [join(here, 'adapter.js')],
	bundle: true,
	format: 'iife',
	target: 'es2019',
	alias: { 'farming-weight': join(library, 'src/index.ts') },
	write: false,
	tsconfigRaw: '{}',
	logLevel: 'warning',
});

// esbuild cannot rewrite classes and loops for an old engine, so TypeScript's compiler does that part.
const lowered = ts.transpileModule(bundled.outputFiles[0].text, {
	compilerOptions: {
		target: ts.ScriptTarget.ES5,
		downlevelIteration: true,
		allowJs: true,
		removeComments: true,
	},
});

const minified = await transform(lowered.outputText, { minifyWhitespace: true, target: 'es5' });

const header =
	`// Generated by tools/fortune/build.mjs. Do not edit.\n` +
	`// Contains farming-weight ${version} (commit ${LIBRARY_COMMIT.slice(0, 12)}),\n` +
	`// Copyright (c) Elite Network Development LLC, MIT License. See FARMING-WEIGHT-LICENSE.txt.\n`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, header + readFileSync(join(here, 'shim.js'), 'utf8') + minified.code);
writeFileSync(join(dirname(output), 'FARMING-WEIGHT-LICENSE.txt'), readFileSync(join(library, 'LICENSE'), 'utf8'));
console.log(`Wrote ${output} (farming-weight ${version})`);
